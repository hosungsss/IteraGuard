"""Generate the v5 execution identity. --check is read-only and detects stale builds."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from integration.v50 import bridge, question_signature, _hash


def artifacts():
    questions = bridge.questions("")["questions"]
    signature = question_signature(questions)
    paths = ["vendor/dmsg/prototype/" + x + ".py" for x in ("model_bridge", "typed_contract", "context_guard", "core")]
    paths += ["integration/v50.py", "apps/shared/dmsg-engine.js", "apps/shared/engine-data.js",
              "apps/shared/v50-contract.js", "linkguard/intake.py", "linkguard/policy.py",
              "apps/shared/dmsg-linkguard.js", "apps/shared/linkguard-data.js"]
    manifest = {
        "schema_version": "dmsg-v50-execution-manifest/1", "trace_schema_version": "dmsg-v50-execution-trace/1",
        "product_version": "5.0.0-development", "release_status": "IMPLEMENTATION_UNDER_VALIDATION",
        "default_policy_id": "legacy", "question_signature": signature,
        "question_contract_sha256": _hash(signature), "question_hash_encoding": "UTF-8 compact JSON ordered arrays; SHA-256",
        "response_schema": bridge.SPEC, "optional_questions": sorted(bridge.OPTIONAL_QUESTIONS),
        "policies": {"legacy": {"id": "legacy", "threshold": .70, "status": "INTERIM_DEFAULT_UNVALIDATED_HEURISTIC"},
                     "dra": {"id": "dra", "version": bridge.DRA_VERSION, "status": "EXPLICIT_COMPARISON_ONLY_DESIGN_COSTS_NOT_VALIDATED"}},
        "guidance_template_sha256": _hash({str(k.value): v for k, v in bridge.MESSAGES.items()}),
        "profiles": {
            "typed": {"current_turn": "legacy_or_explicit_dra", "local_layers": ["USER_REQUESTED_REVIEW", "OFFLINE_LINKGUARD"], "session_guard": "CALLER_RESPONSIBILITY"},
            "on_device_nlp": {"current_turn": "EXISTING_NLP_AND_INDICATOR_PATH", "typed_policy_equivalent": False, "local_layers": ["USER_REQUESTED_REVIEW", "OFFLINE_LINKGUARD"]},
            "local_rules": {"current_turn": "EXISTING_RULES_PATH", "typed_policy_equivalent": False, "local_layers": ["USER_REQUESTED_REVIEW", "OFFLINE_LINKGUARD"]}},
        "runtime": {"model_id": "trillionlabs/Zoro-1", "model_repository": "trillionlabs/Zoro-1",
                    "expected_temperature": 1.52, "temperature_source": "LOCAL_KEV_HEAD_CHECKPOINT_CONFIG; baseline_protocol_20261104",
                    "temperature_observed_by_this_evaluator": False, "model_attested": False,
                    "domain_calibration": "NOT_ESTABLISHED", "client_probability_recalibration": "NONE",
                    "official_revision_reference": "ab05e6c025deb0eed102f42b736dc1589848e6c9",
                    "head_sha256_reference": "01ba32bd7018613b8e3da24963996dbe48950e081af36862af8deaae6d852149",
                    "reference_artifact_is_runtime_attestation": False,
                    "transport": "CALLER_CONFIGURED_TYPED_JSON; evaluator performs no I/O"},
        "team_decisions": {"D01": "HOLD_CURRENT_L2", "D02": "HOLD_G7_ASK_HUMAN", "D03": "HOLD_CLAIM_NOUL", "D04": "L1_APPROVAL_NOT_ESTABLISHED"},
        "source_hashes": {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in paths},
        "source_hash_enforcement": {"python": "READ_AND_VERIFY_AT_EVALUATION", "javascript": "BUILD_CHECK_AND_ORDERED_QUESTION_SIGNATURE_AT_EVALUATION"},
        "privacy": {"trace_raw_text": False, "trace_url": False, "trace_quote": False, "network_in_evaluator": False}}
    manifest["manifest_fingerprint"] = _hash(manifest)
    data = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    js = "// Generated by tools/export_v50_contract.py. Do not edit.\n(function(r){r.DMSG_V50_CONTRACT_DATA=" + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";})(typeof globalThis!=='undefined'?globalThis:this);\n"
    return {ROOT / "configs/v50_contract.json": data, ROOT / "apps/shared/v50-contract-data.js": js}


if __name__ == "__main__":
    check = argparse.ArgumentParser()
    check.add_argument("--check", action="store_true")
    args = check.parse_args()
    stale = []
    for path, value in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != value: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf-8")
    if stale: raise SystemExit("STALE_EXECUTION_CONTRACT: " + ", ".join(stale))
    print("Execution contract " + ("verified" if args.check else "generated"))
