"""Generate frozen question profiles. --check never writes or calls a model."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def artifacts():
    original_path = sys.path[:]
    try:
        sys.path.insert(0, str(ROOT))
        from integration.v51_profiles import build_registry
    finally:
        sys.path[:] = original_path
    data = build_registry()
    formatted = json.dumps(data, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    javascript = ("// Generated by tools/export_v51_profiles.py. Do not edit.\n"
                  "(function(r){r.DMSG_V51_PROFILE_DATA="
                  + json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
                  + ";})(typeof globalThis!=='undefined'?globalThis:this);\n")
    return {ROOT / "configs/v51_profiles.json": formatted,
            ROOT / "apps/shared/v51-profile-data.js": javascript}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("STALE_V51_PROFILES: " + ", ".join(stale))
    print("Question profiles " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
