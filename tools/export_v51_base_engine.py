"""Generate v5.1 Unicode-compatible copies without changing frozen v5 sources."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError("V51_BASE_ENGINE_SOURCE_SHAPE_CHANGED")
    return source.replace(old, new, 1)


def artifacts():
    engine_path = ROOT / "apps/shared/dmsg-engine.js"
    contract_path = ROOT / "apps/shared/v50-contract.js"
    engine = engine_path.read_text(encoding="utf-8")
    contract = contract_path.read_text(encoding="utf-8")
    helper = """
  // Only the lexical token comparison differs from the frozen v5 JS copy.
  var V51_CASEFOLD_DATA = globalThis.DMSG_V51_RULE_DATA ||
    (typeof require === 'function' ? (require('./v51-semantic-data.js'), globalThis.DMSG_V51_RULE_DATA) : null);
  if (!V51_CASEFOLD_DATA || !V51_CASEFOLD_DATA.casefold_map) throw new Error('V51_CASEFOLD_DATA_MISSING');
  function v51Casefold(text) {
    var table = V51_CASEFOLD_DATA.casefold_map;
    return Array.from(text).map(function(c) { return table[c] === undefined ? c : table[c]; }).join('');
  }
"""
    engine = replace_once(engine, "root.DMSG = api;", "root.DMSG_V51_BASE_ENGINE = api;")
    engine = replace_once(engine, "  'use strict';", "  'use strict';" + helper)
    engine = replace_once(engine, "var TOKENS = G.action_tokens.map(function (t) { return t.toLowerCase(); });",
                          "var TOKENS = G.action_tokens.map(function (t) { return v51Casefold(t); });")
    engine = replace_once(engine, "var folded = text.toLowerCase();", "var folded = v51Casefold(text);")
    contract = replace_once(contract, "var E=root.DMSG ||", "var E=root.DMSG_V51_BASE_ENGINE ||")
    contract = replace_once(contract, "require('./dmsg-engine.js')", "require('./v51-base-engine.js')")
    contract = replace_once(contract, "root.DMSG_V50=api;", "root.DMSG_V51_BASE_CONTRACT=api;")
    def header(path):
        return ("// Generated by tools/export_v51_base_engine.py. Do not edit.\n"
                "// Frozen source SHA256: " + hashlib.sha256(path.read_bytes()).hexdigest() + "\n")
    return {ROOT / "apps/shared/v51-base-engine.js": header(engine_path) + engine,
            ROOT / "apps/shared/v51-base-contract.js": header(contract_path) + contract}


def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true")
    args = parser.parse_args(); stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content, encoding="utf-8")
    if stale: raise SystemExit("STALE_V51_BASE_ENGINE: " + ", ".join(stale))
    print("v5.1 base engine " + ("verified" if args.check else "generated"))


if __name__ == "__main__": main()
