"""Write apps/shared/linkguard-data.js from the Python reference (single source of truth for LinkGuard data)."""
import hashlib, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from linkguard import intake as LI, policy as PO  # noqa: E402

def main():
    D = {'max_text': LI.MAX_TEXT, 'max_urls': LI.MAX_URLS, 'tlds': LI.TLDS, 'two_level_suffixes': LI.TWO_LEVEL_SUFFIXES,
         'shorteners': LI.SHORTENERS, 'messenger_hosts': LI.MESSENGER_HOSTS, 'app_store_hosts': LI.APP_STORE_HOSTS,
         'brands': LI.BRANDS, 'sensitive_keys': LI.SENSITIVE_KEYS, 'scheme_class': LI.SCHEME_CLASS,
         'v4_reserved': [list(x) for x in LI.V4_RESERVED], 'confusables': LI.CONFUSABLES,
         'policy': {'rank': PO.RANK, 'suspicious_url_flags': PO.SUSPICIOUS_URL_FLAGS, 'caution_url_flags': PO.CAUTION_URL_FLAGS,
                    'web_analysis_status': PO.WEB_ANALYSIS_STATUS, 'action_rank': PO.ACTION_RANK, 'link_to_action': PO.LINK_TO_ACTION},
         'source_sha256': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in ('linkguard/intake.py', 'linkguard/policy.py')}}
    body = json.dumps(D, ensure_ascii=False, sort_keys=False)
    out = ROOT / 'apps/shared/linkguard-data.js'
    out.write_text('/* generated by tools/linkguard/export_linkguard_data.py — do not edit */\n'
                   '(typeof globalThis !== "undefined" ? globalThis : this).LINKGUARD_DATA = ' + body + ';\n', encoding='utf8')
    print(out.relative_to(ROOT), len(body))

if __name__ == '__main__':
    main()
