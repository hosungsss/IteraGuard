"""Generate the semantic policy's rules, Python Unicode behavior, and source IDs."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def _character_class(predicate):
    ranges = []
    start = end = None
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if start is None: start = end = cp
            elif cp == end + 1: end = cp
            else: ranges.append((start, end)); start = end = cp
    if start is not None: ranges.append((start, end))
    def escaped(cp): return r"\u{" + format(cp, "x") + "}"
    return "[" + "".join(escaped(lo) if lo == hi else escaped(lo) + "-" + escaped(hi) for lo, hi in ranges) + "]"


def artifacts():
    rules = json.loads((ROOT / "configs/v51_semantic_rules.json").read_text(encoding="utf-8"))
    digits = _character_class(lambda c: unicodedata.category(c) == "Nd")
    space = _character_class(str.isspace)
    word = _character_class(lambda c: c.isalnum() or c == "_")
    folds = {chr(cp): chr(cp).casefold() for cp in range(0x110000) if chr(cp).casefold() != chr(cp)}
    tree = ast.parse((ROOT / "integration/v51_policy.py").read_text(encoding="utf-8"))
    patterns = [node.args[0].value for node in ast.walk(tree) if isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name)
                and node.func.value.id == "re" and node.func.attr == "search"
                and node.args and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)]
    def policy_regex(prefix):
        matches = [p for p in patterns if p.startswith(prefix)]
        if len(matches) != 1: raise ValueError("UNRECOGNIZED_SEMANTIC_REGEX")
        # Python re.I additionally equates ASCII i/s/k with these code points.
        return matches[0].replace(r"\s", space).replace("i", r"[iI\u0130\u0131]").replace("s", r"[sS\u017f]").replace("k", r"[kK\u212a]")
    data = {"schema_version": "dmsg-v51-semantic-js-data/1", "rules": rules,
            "python_unicode_version": unicodedata.unidata_version, "casefold_map": folds,
            "regex": {"payment_amount": digits + "(?:" + digits + "|[,.])*" + space + "*(?:만|천|억)?" + space + "*원",
                      "url": r"https?://|www\.|[A-Za-z0-9.\-\u0130\u0131\u017f\u212a]+\.(?:com|net|org|kr)(?:/|(?!" + word + "))",
                      "direct_exposure": policy_regex("알려|입력|"),
                      "payment_verb": policy_regex("송금|이체|"),
                      "explicit_anomaly": policy_regex("임시|보호용|"),
                      "other_request": policy_regex("주세요|주십시오|"),
                      "indirect_redirect": policy_regex("(?:아래|첨부|")},
            "source_hashes": {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in (
                "integration/v51_policy.py", "configs/v51_semantic_rules.json",
                "apps/shared/v51-semantic.js", "tools/export_v51_semantic.py",
                "tools/export_v51_base_engine.py", "apps/shared/v51-base-engine.js", "apps/shared/v51-base-contract.js",
                "apps/shared/dmsg-engine.js", "apps/shared/engine-data.js")}}
    encoded = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    data["fingerprint"] = hashlib.sha256(encoded.encode("utf-8")).hexdigest()
    content = ("// Generated by tools/export_v51_semantic.py. Do not edit.\n"
               "(function(r){r.DMSG_V51_RULE_DATA="
               + json.dumps(data, ensure_ascii=False, separators=(",", ":"))
               + ";})(typeof globalThis!=='undefined'?globalThis:this);\n")
    return {ROOT / "apps/shared/v51-semantic-data.js": content}


def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true")
    args = parser.parse_args(); stale = []
    for path, content in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content, encoding="utf-8")
    if stale: raise SystemExit("STALE_V51_SEMANTIC_DATA: " + ", ".join(stale))
    print("Semantic data " + ("verified" if args.check else "generated"))


if __name__ == "__main__": main()
